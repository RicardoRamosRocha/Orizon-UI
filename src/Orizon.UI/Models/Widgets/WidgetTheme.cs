namespace Orizon.UI.Models.Widgets;

/// <summary>
/// Defines the semantic themes available to widgets.
/// </summary>
public enum WidgetTheme
{
    /// <summary>
    /// The default theme.
    /// </summary>
    Default,

    /// <summary>
    /// The primary theme.
    /// </summary>
    Primary,

    /// <summary>
    /// The secondary theme.
    /// </summary>
    Secondary,

    /// <summary>
    /// The success theme.
    /// </summary>
    Success,

    /// <summary>
    /// The warning theme.
    /// </summary>
    Warning,

    /// <summary>
    /// The danger theme.
    /// </summary>
    Danger,

    /// <summary>
    /// The informational theme.
    /// </summary>
    Info
}
